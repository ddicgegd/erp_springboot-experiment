-- V16: Add APPLICABLE_SKUS column to VOUCHERS table
-- Oracle DB DDL Migration Script

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'VOUCHERS' AND COLUMN_NAME = 'APPLICABLE_SKUS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE VOUCHERS ADD (APPLICABLE_SKUS VARCHAR2(1000))';
  END IF;
END;
/
