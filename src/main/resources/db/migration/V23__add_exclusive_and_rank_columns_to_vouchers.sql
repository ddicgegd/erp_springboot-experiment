-- V23: Add IS_EXCLUSIVE and MIN_REQUIRED_RANK columns to VOUCHERS table
-- Oracle DB DDL Migration Script

DECLARE
  v_count NUMBER;
BEGIN
  -- 1. Check and add IS_EXCLUSIVE column (NUMBER(1) with default 0 for boolean)
  SELECT COUNT(*) INTO v_count 
  FROM USER_TAB_COLUMNS 
  WHERE TABLE_NAME = 'VOUCHERS' AND COLUMN_NAME = 'IS_EXCLUSIVE';
  
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE VOUCHERS ADD (IS_EXCLUSIVE NUMBER(1) DEFAULT 0 NOT NULL)';
  END IF;

  -- 2. Check and add MIN_REQUIRED_RANK column (VARCHAR2(50) with default MEMBER)
  SELECT COUNT(*) INTO v_count 
  FROM USER_TAB_COLUMNS 
  WHERE TABLE_NAME = 'VOUCHERS' AND COLUMN_NAME = 'MIN_REQUIRED_RANK';
  
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE VOUCHERS ADD (MIN_REQUIRED_RANK VARCHAR2(50) DEFAULT ''MEMBER'' NOT NULL)';
  END IF;
END;
/
