-- V9: Alter ORDERS table to support multiple discount codes (DISCOUNT_CODES VARCHAR2(500))
-- Oracle DB DDL Migration

DECLARE
  v_count NUMBER;
BEGIN
  -- Check if DISCOUNT_CODES already exists
  SELECT COUNT(*)
    INTO v_count
    FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'ORDERS'
     AND COLUMN_NAME = 'DISCOUNT_CODES';

  IF v_count = 0 THEN
    -- Check if old DISCOUNT_CODE exists
    SELECT COUNT(*)
      INTO v_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'ORDERS'
       AND COLUMN_NAME = 'DISCOUNT_CODE';

    IF v_count > 0 THEN
      -- Rename old column to DISCOUNT_CODES and expand size to 500
      EXECUTE IMMEDIATE 'ALTER TABLE ORDERS RENAME COLUMN DISCOUNT_CODE TO DISCOUNT_CODES';
      EXECUTE IMMEDIATE 'ALTER TABLE ORDERS MODIFY (DISCOUNT_CODES VARCHAR2(500))';
    ELSE
      -- Add new column DISCOUNT_CODES
      EXECUTE IMMEDIATE 'ALTER TABLE ORDERS ADD (DISCOUNT_CODES VARCHAR2(500))';
    END IF;
  ELSE
    EXECUTE IMMEDIATE 'ALTER TABLE ORDERS MODIFY (DISCOUNT_CODES VARCHAR2(500))';
  END IF;
END;
/
