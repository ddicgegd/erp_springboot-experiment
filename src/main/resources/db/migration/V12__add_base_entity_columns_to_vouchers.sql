-- V12: Add BaseEntity soft-delete and audit columns to VOUCHERS table
-- Oracle DB DDL Migration Script

DECLARE
  v_count NUMBER;
BEGIN
  -- Check and add IS_DELETED
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'VOUCHERS' AND COLUMN_NAME = 'IS_DELETED';
