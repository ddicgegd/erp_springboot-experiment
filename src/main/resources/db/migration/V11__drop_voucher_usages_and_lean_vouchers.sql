-- V11: Simplify VOUCHERS table and DROP VOUCHERS_USAGES / VOUCHER_USAGES table in Oracle DB
-- Oracle DB DDL Migration Script

DECLARE
  v_count NUMBER;
BEGIN
  -- 1. Drop VOUCHERS_USAGES table if exists
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'VOUCHERS_USAGES';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'DROP TABLE VOUCHERS_USAGES CASCADE CONSTRAINTS';
  END IF;

  -- Drop VOUCHER_USAGES table if exists
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'VOUCHER_USAGES';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'DROP TABLE VOUCHER_USAGES CASCADE CONSTRAINTS';
  END IF;

  -- 2. Clean up columns in VOUCHERS table if they exist
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'VOUCHERS' AND COLUMN_NAME = 'RESERVED_QUANTITY';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE VOUCHERS DROP COLUMN RESERVED_QUANTITY';
  END IF;

  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'VOUCHERS' AND COLUMN_NAME = 'MAX_USAGE_PER_USER';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE VOUCHERS DROP COLUMN MAX_USAGE_PER_USER';
  END IF;

  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'VOUCHERS' AND COLUMN_NAME = 'APPLICABLE_SKUS';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE VOUCHERS DROP COLUMN APPLICABLE_SKUS';
  END IF;
END;
/
