-- V10: Create VOUCHERS and VOUCHER_USAGES tables in Oracle DB
-- Oracle DB DDL Migration Script

DECLARE
  v_count NUMBER;
BEGIN
  -- 1. Create VOUCHERS table
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'VOUCHERS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE VOUCHERS (
        ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        CODE VARCHAR2(100) NOT NULL UNIQUE,
        NAME VARCHAR2(255) NOT NULL,
        DESCRIPTION VARCHAR2(500),
        VOUCHER_TYPE VARCHAR2(50) NOT NULL,
        DISCOUNT_TYPE VARCHAR2(50) NOT NULL,
        DISCOUNT_VALUE NUMBER(19,4) NOT NULL,
        MAX_DISCOUNT_AMOUNT NUMBER(19,4),
        MIN_ORDER_AMOUNT NUMBER(19,4) DEFAULT 0,
        START_DATE TIMESTAMP NOT NULL,
        END_DATE TIMESTAMP NOT NULL,
        TOTAL_QUANTITY NUMBER(10) DEFAULT 0 NOT NULL,
        USED_QUANTITY NUMBER(10) DEFAULT 0 NOT NULL,
        RESERVED_QUANTITY NUMBER(10) DEFAULT 0 NOT NULL,
        MAX_USAGE_PER_USER NUMBER(10) DEFAULT 1 NOT NULL,
        APPLICABLE_SKUS VARCHAR2(1000),
        IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
        CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        CREATED_BY VARCHAR2(100),
        UPDATED_BY VARCHAR2(100)
      )
    ';
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_VOUCHER_TYPE ON VOUCHERS(VOUCHER_TYPE)';
  END IF;

  -- 2. Create VOUCHER_USAGES table
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'VOUCHER_USAGES';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE VOUCHERS_USAGES (
        ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        VOUCHER_ID NUMBER(19) NOT NULL,
        VOUCHER_CODE VARCHAR2(100) NOT NULL,
        RESERVATION_ID VARCHAR2(100) NOT NULL,
        ORDER_NUMBER VARCHAR2(100),
        CUSTOMER_ID VARCHAR2(100),
        DISCOUNT_AMOUNT NUMBER(19,4) DEFAULT 0,
        STATUS VARCHAR2(50) NOT NULL,
        RESERVED_AT TIMESTAMP NOT NULL,
        EXPIRES_AT TIMESTAMP NOT NULL,
        COMMITTED_AT TIMESTAMP,
        RELEASED_AT TIMESTAMP,
        CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        CREATED_BY VARCHAR2(100),
        UPDATED_BY VARCHAR2(100),
        CONSTRAINT FK_VU_VOUCHER FOREIGN KEY (VOUCHER_ID) REFERENCES VOUCHERS(ID) ON DELETE CASCADE
      )
    ';
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_VU_VOUCHER_ID ON VOUCHERS_USAGES(VOUCHER_ID)';
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_VU_RESERVATION_ID ON VOUCHERS_USAGES(RESERVATION_ID)';
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_VU_ORDER_NUMBER ON VOUCHERS_USAGES(ORDER_NUMBER)';
  END IF;
END;
/
