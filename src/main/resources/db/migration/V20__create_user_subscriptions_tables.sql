-- 1. Bảng lưu trữ Payment Profile của khách hàng (Vaulted Token gắn với User)
CREATE TABLE customer_payment_profiles (
    id VARCHAR2(64) PRIMARY KEY,
    user_id NUMBER(19, 0) NOT NULL,
    gateway VARCHAR2(50) NOT NULL,
    multi_use_token VARCHAR2(255) NOT NULL,
    fpan_last_four VARCHAR2(4),
    card_network VARCHAR2(50),
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    initial_cit_transaction_id VARCHAR2(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by VARCHAR2(100),
    updated_by VARCHAR2(100),
    CONSTRAINT fk_payment_profile_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_payment_profile_user ON customer_payment_profiles(user_id);
CREATE INDEX idx_payment_profile_token ON customer_payment_profiles(multi_use_token);

-- 2. Bảng định nghĩa các gói Subscription (3, 6, 12 tháng + 1M Free Trial)
CREATE TABLE subscription_plans (
    id NUMBER(19, 0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    plan_code VARCHAR2(50) NOT NULL UNIQUE,
    name VARCHAR2(100) NOT NULL,
    target_rank VARCHAR2(30) NOT NULL,
    billing_period_months NUMBER(10, 0) NOT NULL,
    free_trial_days NUMBER(10, 0) DEFAULT 30 NOT NULL,
    price_amount NUMBER(15, 2) NOT NULL,
    currency VARCHAR2(10) DEFAULT 'VND' NOT NULL,
    is_active NUMBER(1, 0) DEFAULT 1 NOT NULL,
    description VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by VARCHAR2(100),
    updated_by VARCHAR2(100)
);

-- 3. Bảng quản lý Subscription của người dùng
CREATE TABLE user_subscriptions (
    id NUMBER(19, 0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19, 0) NOT NULL,
    plan_id NUMBER(19, 0) NOT NULL,
    payment_profile_id VARCHAR2(64),
    subscription_state VARCHAR2(30) NOT NULL,
    is_trial NUMBER(1, 0) DEFAULT 0 NOT NULL,
    start_time TIMESTAMP NOT NULL,
    expiry_time TIMESTAMP NOT NULL,
    auto_renewing NUMBER(1, 0) DEFAULT 1 NOT NULL,
    cancellation_reason VARCHAR2(500),
    last_payment_time TIMESTAMP,
    last_fineract_journal_id VARCHAR2(64),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by VARCHAR2(100),
    updated_by VARCHAR2(100),
    CONSTRAINT fk_user_subs_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_subs_plan FOREIGN KEY (plan_id) REFERENCES subscription_plans(id)
);

CREATE INDEX idx_user_subs_user_state ON user_subscriptions(user_id, subscription_state);
CREATE INDEX idx_user_subs_profile ON user_subscriptions(payment_profile_id);
CREATE INDEX idx_user_subs_expiry ON user_subscriptions(expiry_time);

-- 4. Bảng Audit Log ghi nhận các giao dịch và thay đổi trạng thái
CREATE TABLE subscription_audit_logs (
    id NUMBER(19, 0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19, 0),
    subscription_id NUMBER(19, 0),
    event_type VARCHAR2(50) NOT NULL,
    previous_state VARCHAR2(30),
    new_state VARCHAR2(30),
    amount NUMBER(15, 2),
    currency VARCHAR2(10),
    fineract_journal_id VARCHAR2(64),
    payload CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by VARCHAR2(100),
    updated_by VARCHAR2(100)
);

CREATE INDEX idx_sub_audit_user ON subscription_audit_logs(user_id);
CREATE INDEX idx_sub_audit_sub_id ON subscription_audit_logs(subscription_id);

