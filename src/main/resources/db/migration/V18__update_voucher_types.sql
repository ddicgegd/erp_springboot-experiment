-- V18: Update existing voucher_type from PRODUCT to PRODUCT_ITEM
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'VOUCHERS';
  IF v_count > 0 THEN
    UPDATE VOUCHERS SET VOUCHER_TYPE = 'PRODUCT_ITEM' WHERE VOUCHER_TYPE = 'PRODUCT';
    COMMIT;
  END IF;
END;
/
