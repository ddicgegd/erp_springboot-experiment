    EXECUTE IMMEDIATE 'ALTER TABLE VOUCHERS ADD (IS_DELETED NUMBER(1) DEFAULT 0 NOT NULL)';
  END IF;

  -- Check and add DELETED_AT
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'VOUCHERS' AND COLUMN_NAME = 'DELETED_AT';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE VOUCHERS ADD (DELETED_AT TIMESTAMP)';
  END IF;

  -- Check and add DELETED_BY
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'VOUCHERS' AND COLUMN_NAME = 'DELETED_BY';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE VOUCHERS ADD (DELETED_BY VARCHAR2(100))';
  END IF;

  -- Check and add UPDATE_HISTORY
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'VOUCHERS' AND COLUMN_NAME = 'UPDATE_HISTORY';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE VOUCHERS ADD (UPDATE_HISTORY CLOB)';
  END IF;
END;
