-- V14: Create VOUCHERS_SEQ sequence for Hibernate Oracle validation
-- Oracle DB DDL Migration Script

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'VOUCHERS_SEQ';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE VOUCHERS_SEQ START WITH 1 INCREMENT BY 50 NOCACHE NOCYCLE';
  END IF;
END;
/
