-- Drop OrderItem name snapshot columns. The application no longer maps or returns them.

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_count
    FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'ORDER_ITEMS'
     AND COLUMN_NAME = 'ATTRIBUTES_NAME';

  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ORDER_ITEMS DROP COLUMN ATTRIBUTES_NAME';
  END IF;
END;
/

DECLARE
  v_count NUMBER;
